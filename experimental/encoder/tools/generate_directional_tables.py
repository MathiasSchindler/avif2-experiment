#!/usr/bin/env python3
"""Generate classic AV2 directional tables from the published specification."""

from __future__ import annotations

import argparse
import hashlib
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT.parents[1] / "docs/spec/av2-v1.0.0/attachments"
OUTPUT = ROOT / "src/normative_directional.inc"
HASHES = {
    "dr_intra_derivative.h":
        "1820b55f70dac00ab8ece6346578459c69babfb31f4c924acad5d35037b17504",
    "mode_to_angle.h":
        "9efe566b675179962f57ac5ef6895c256e83ab088466ae029757da7c233995b6",
}
INTERP = (
    (0, 128, 0, 0), (-2, 127, 4, -1), (-3, 125, 8, -2),
    (-5, 123, 13, -3), (-6, 121, 17, -4), (-7, 118, 22, -5),
    (-9, 116, 27, -6), (-9, 112, 32, -7), (-10, 109, 37, -8),
    (-11, 106, 41, -8), (-11, 102, 46, -9), (-12, 98, 52, -10),
    (-12, 94, 56, -10), (-12, 90, 61, -11), (-12, 85, 66, -11),
    (-12, 81, 71, -12), (-12, 76, 76, -12), (-12, 71, 81, -12),
    (-11, 66, 85, -12), (-11, 61, 90, -12), (-10, 56, 94, -12),
    (-10, 52, 98, -12), (-9, 46, 102, -11), (-8, 41, 106, -11),
    (-8, 37, 109, -10), (-7, 32, 112, -9), (-6, 27, 116, -9),
    (-5, 22, 118, -7), (-4, 17, 121, -6), (-3, 13, 123, -5),
    (-2, 8, 125, -3), (-1, 4, 127, -2),
)


def values(name: str, count: int) -> list[int]:
    path = SPEC / name
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    if digest != HASHES[name]:
        raise ValueError(f"{name}: sha256 {digest}, expected {HASHES[name]}")
    found = [int(value) for value in re.findall(r"-?\d+", path.read_text())]
    result = found[-count:]
    if len(result) != count:
        raise ValueError(f"{name}: expected {count} values")
    return result


def render() -> str:
    derivative = values("dr_intra_derivative.h", 90)
    angles = values("mode_to_angle.h", 13)
    rows = ",\n".join(
        "    {" + ", ".join(str(value) for value in row) + "}"
        for row in INTERP)
    return (
        "/* Generated by tools/generate_directional_tables.py from AV2 v1.0.0\n"
        " * attachments and section 7.13.2.8. CC0-1.0. */\n"
        "static const uint16_t directional_derivative[90U] = {\n    " +
        ", ".join(str(value) for value in derivative) + "\n};\n"
        "static const uint8_t directional_mode_angle[13U] = {\n    " +
        ", ".join(str(value) for value in angles) + "\n};\n"
        "static const int16_t directional_interp[32U][4U] = {\n" +
        rows + "\n};\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render()
    if args.check:
        return 0 if OUTPUT.read_text(encoding="ascii") == generated else 1
    OUTPUT.write_text(generated, encoding="ascii")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
