#!/usr/bin/env python3
"""Generate the CC0 16-point inverse DCT basis from its cosine definition."""

from __future__ import annotations

import argparse
import math
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/normative_dct16.inc"


def matrix() -> list[list[int]]:
    rows = []
    for frequency in range(16):
        scale = 64.0 if frequency == 0 else 64.0 * math.sqrt(2.0)
        rows.append([
            round(scale * math.cos(
                math.pi * (2 * output + 1) * frequency / 32.0))
            for output in range(16)
        ])
    return rows


def render() -> str:
    body = ",\n".join(
        "    {" + ", ".join(str(value) for value in row) + "}"
        for row in matrix())
    return (
        "/* Generated by tools/generate_dct16.py from the orthonormal\n"
        " * 16-point DCT-II cosine definition, scaled by 64. CC0-1.0. */\n"
        "static const int16_t dct16[16U][16U] = {\n"
        f"{body}\n"
        "};\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render()
    if args.check:
        return 0 if OUTPUT.read_text(encoding="ascii") == generated else 1
    OUTPUT.write_text(generated, encoding="ascii")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
