#!/usr/bin/env python3
import argparse
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE = ROOT / "vendor/avm/av2/common/entropy_inits_coeffs.h"
DEFAULT_OUTPUT = ROOT / "src/decoder/fsc_cdf_data.inc"

TABLES = (
    ("av2_default_coeff_base_bob_multi_cdfs", "fsc_bob_specs", 3, 36),
    ("av2_default_coeff_base_multi_cdfs_idtx", "fsc_base_specs", 4, 84),
    ("av2_default_coeff_lps_multi_cdfs_idtx", "fsc_br_specs", 4, 84),
    ("av2_default_idtx_sign_cdfs", "fsc_sign_specs", 2, 108),
)

PARAMETER_DIGIT = {0: 0, -1: 1, -2: 2, 1: 3}


def initializer(source: str, name: str) -> str:
    start = source.index(name)
    opening = source.index("{", source.index("=", start))
    depth = 0
    for index in range(opening, len(source)):
        if source[index] == "{":
            depth += 1
        elif source[index] == "}":
            depth -= 1
            if depth == 0:
                return source[opening : index + 1]
    raise ValueError(f"unterminated initializer: {name}")


def parse_table(source: str, name: str, symbols: int, count: int):
    body = initializer(source, name)
    pattern = re.compile(
        rf"AVM_CDF{symbols}\(([^)]*)\)\s*,\s*"
        rf"AVM_PARA{symbols}\(([^)]*)\)"
    )
    entries = []
    for match in pattern.finditer(body):
        thresholds = [int(value.strip()) for value in match.group(1).split(",")]
        parameters = [int(value.strip()) for value in match.group(2).split(",")]
        if len(thresholds) != symbols - 1 or len(parameters) != 3:
            raise ValueError(f"malformed entry in {name}")
        try:
            parameter = (
                PARAMETER_DIGIT[parameters[0]] * 25
                + PARAMETER_DIGIT[parameters[1]] * 5
                + PARAMETER_DIGIT[parameters[2]]
            )
        except KeyError as error:
            raise ValueError(f"unsupported parameter in {name}: {error.args[0]}")
        thresholds.extend([0] * (3 - len(thresholds)))
        entries.append((thresholds, parameter))
    if len(entries) != count:
        raise ValueError(f"{name}: expected {count} entries, found {len(entries)}")
    return entries


def render(source_path: Path) -> str:
    source = source_path.read_text(encoding="utf-8")
    lines = [
        "/* Generated by tools/generate_fsc_cdf_tables.py from pinned AVM. */",
        "",
    ]
    for avm_name, local_name, symbols, count in TABLES:
        entries = parse_table(source, avm_name, symbols, count)
        lines.append(
            f"static const Av2hFscCdfSpec {local_name}[{count}U] = {{"
        )
        for thresholds, parameter in entries:
            lines.append(
                "    { { "
                + ", ".join(f"{value}U" for value in thresholds)
                + f" }}, {parameter}U }},"
            )
        lines.extend(("};", ""))
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(args.source), encoding="ascii", newline="\n")


if __name__ == "__main__":
    main()
