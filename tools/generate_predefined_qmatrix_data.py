#!/usr/bin/env python3
"""Extract pinned AVM's predefined inverse quantization matrices."""

from __future__ import annotations

import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "vendor/avm/av2/common/predefined_qm.c"
OUTPUT = ROOT / "src/decoder/predefined_qmatrix.inc"
LEVELS = 15
PLANES = 2
VALUES_PER_MATRIX = 3600


def main() -> None:
    source = SOURCE.read_text(encoding="ascii")
    start = source.index("predefined_iwt_matrix_ref")
    start = source.index("= {", start) + 3
    end = source.index("predefined_wt_matrix_ref", start)
    initializer = source[start:end]
    initializer = re.sub(r"/\*.*?\*/", "", initializer, flags=re.DOTALL)
    initializer = re.sub(r"//.*", "", initializer)
    values = [int(value) for value in re.findall(r"\b\d+\b", initializer)]
    expected = LEVELS * PLANES * VALUES_PER_MATRIX
    if len(values) != expected or any(value < 1 or value > 255 for value in values):
        raise RuntimeError(
            f"unexpected inverse matrix data: got {len(values)}, expected {expected}"
        )

    lines = [
        "/* Generated by tools/generate_predefined_qmatrix_data.py. */",
        "static const uint8_t av2h_predefined_iqmatrix[15][2][3600] = {",
    ]
    index = 0
    for level in range(LEVELS):
        lines.append("    {")
        for plane in range(PLANES):
            lines.append("        {")
            matrix = values[index : index + VALUES_PER_MATRIX]
            index += VALUES_PER_MATRIX
            for offset in range(0, len(matrix), 16):
                row = ", ".join(f"{value}U" for value in matrix[offset : offset + 16])
                lines.append(f"            {row},")
            lines.append("        },")
        lines.append("    },")
    lines.append("};")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="ascii")


if __name__ == "__main__":
    main()